#!/usr/bin/env python
"""Can model A hand a half-finished latent to model B? Check WITHOUT a GPU.

For each pair we compare three things, straight from the Hugging Face Hub:
  1. VAE config: latent_channels, scaling_factor, shift_factor, latents_mean/std
  2. VAE weight fingerprint: the LFS SHA-256 of the fp16 safetensors, and with
     --deep a tensor-by-tensor comparison (a file hash can differ just because
     of header metadata, so --deep is the real answer)
  3. Scheduler config: _class_name, beta_schedule, prediction_type, timestep_spacing

Also compares text encoders (needed for the one-pipeline UNet-swap implementation).

    python bench/compat_check.py            # configs + file hashes (seconds)
    python bench/compat_check.py --deep     # also download VAEs/text encoders and compare tensors (~2 GB)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

from huggingface_hub import HfApi, hf_hub_download

MODELS = {
    "SDXL":        "stabilityai/stable-diffusion-xl-base-1.0",
    "SSD-1B":      "segmind/SSD-1B",
    "Vega":        "segmind/Segmind-Vega",
    "Playground":  "playgroundai/playground-v2.5-1024px-aesthetic",
    "SD1.5":       "stable-diffusion-v1-5/stable-diffusion-v1-5",
}
PAIRS = [("SSD-1B", "SDXL"), ("SSD-1B", "Vega"), ("SDXL", "Playground"), ("SD1.5", "SDXL")]
VAE_KEYS = ["latent_channels", "scaling_factor", "shift_factor", "latents_mean", "latents_std", "force_upcast"]
SCHED_KEYS = ["_class_name", "beta_schedule", "prediction_type", "timestep_spacing", "num_train_timesteps", "beta_start", "beta_end"]


def cfg(repo: str, sub: str, name: str) -> dict:
    return json.loads(Path(hf_hub_download(repo, f"{sub}/{name}")).read_text())


def file_sha(api: HfApi, repo: str, path: str) -> str:
    info = api.model_info(repo, files_metadata=True)
    for s in info.siblings:
        if s.rfilename == path:
            return s.lfs.sha256[:12] if s.lfs else "(not lfs)"
    return "(missing)"


def tensor_hashes(repo: str, path: str) -> dict:
    fp = hf_hub_download(repo, path)
    with open(fp, "rb") as f:
        n = struct.unpack("<Q", f.read(8))[0]
        header = json.loads(f.read(n)); header.pop("__metadata__", None)
        out = {}
        for name, info in header.items():
            s, e = info["data_offsets"]; f.seek(8 + n + s)
            out[name] = (hashlib.sha256(f.read(e - s)).hexdigest(), tuple(info["shape"]), info["dtype"])
    return out


def deep_compare(a: str, b: str, path: str, b_path: str | None = None) -> str:
    """Numeric comparison of shared tensors. Interpreting the result:
    max|d| ~ 1e-2 on fp16 weights  -> same weights, different save path (rounding)
    max|d| >> 1 or mean|d| > 1e-3  -> genuinely different weights."""
    import numpy as np
    from safetensors.numpy import load_file
    A = load_file(hf_hub_download(a, path)); B = load_file(hf_hub_download(b, b_path or path))
    mx = tot = n = 0.0
    for k, va in A.items():
        if k not in B:
            continue
        d = np.abs(va.astype(np.float32) - B[k].astype(np.float32))
        mx = max(mx, float(d.max())); tot += float(d.sum()); n += d.size
    mean = tot / max(n, 1)
    verdict = "SAME WEIGHTS (rounding only)" if mx < 0.1 and mean < 1e-3 else "DIFFERENT WEIGHTS"
    return f"{verdict}: max|d|={mx:.3g}, mean|d|={mean:.2g}"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--deep", action="store_true")
    ap.add_argument("--out", default="docs/compat_report.md")
    args = ap.parse_args(argv)
    api = HfApi()

    info = {}
    for name, repo in MODELS.items():
        v, s = cfg(repo, "vae", "config.json"), cfg(repo, "scheduler", "scheduler_config.json")
        info[name] = dict(repo=repo, vae={k: v.get(k) for k in VAE_KEYS}, sched={k: s.get(k) for k in SCHED_KEYS},
                          vae_sha=file_sha(api, repo, "vae/diffusion_pytorch_model.fp16.safetensors"),
                          te_sha=file_sha(api, repo, "text_encoder/model.fp16.safetensors"),
                          te2_sha=file_sha(api, repo, "text_encoder_2/model.fp16.safetensors"))

    lines = ["# Handoff compatibility report", "", "Generated by `bench/compat_check.py`.", "",
             "## Per-model facts", "", "| model | latent ch | scaling | shift | scheduler | beta | prediction | spacing | VAE sha | TE sha | TE2 sha |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for n, i in info.items():
        v, s = i["vae"], i["sched"]
        lines.append(f"| {n} | {v['latent_channels']} | {v['scaling_factor']} | {v['shift_factor']} | {s['_class_name']} | {s['beta_schedule']} | {s['prediction_type']} | {s['timestep_spacing']} | `{i['vae_sha']}` | `{i['te_sha']}` | `{i['te2_sha']}` |")

    lines += ["", "## Pair verdicts", "", "| A -> B | same latent format? | same schedule? | VAE weights | text encoders | verdict |", "|---|---|---|---|---|---|"]
    for a, b in PAIRS:
        ia, ib = info[a], info[b]
        fmt = ia["vae"]["latent_channels"] == ib["vae"]["latent_channels"] and ia["vae"]["scaling_factor"] == ib["vae"]["scaling_factor"] and ia["vae"]["shift_factor"] == ib["vae"]["shift_factor"]
        sched = all(ia["sched"][k] == ib["sched"][k] for k in ("beta_schedule", "prediction_type", "num_train_timesteps")) and ia["sched"]["_class_name"].replace("EDM", "") == ib["sched"]["_class_name"].replace("EDM", "") and ("EDM" in ia["sched"]["_class_name"]) == ("EDM" in ib["sched"]["_class_name"])
        if args.deep:
            vae = deep_compare(ia["repo"], ib["repo"], "vae/diffusion_pytorch_model.fp16.safetensors")
            te = deep_compare(ia["repo"], ib["repo"], "text_encoder/model.fp16.safetensors") if ia["te2_sha"] != "(missing)" and ib["te2_sha"] != "(missing)" else "n/a (different encoder stack)"
        else:
            vae = "same file hash" if ia["vae_sha"] == ib["vae_sha"] else "file hash differs (run --deep)"
            te = "same file hash" if ia["te_sha"] == ib["te_sha"] and ia["te2_sha"] == ib["te2_sha"] else "file hash differs (run --deep)"
        if not fmt:
            verdict = "IMPOSSIBLE / pixel bridge only (different latent format)"
        elif not sched:
            verdict = "BREAKS without schedule conversion (pixel bridge, or convert sigmas)"
        elif args.deep and vae.startswith("DIFFERENT"):
            verdict = "DIFFERENT VAE WEIGHTS: check whether one is sdxl-vae-fp16-fix (same latent space) before trusting a latent handoff"
        else:
            verdict = "SHOULD WORK (verify with a real handoff image)"
        lines.append(f"| {a} -> {b} | {'yes' if fmt else 'NO'} | {'yes' if sched else 'NO'} | {vae} | {te} | {verdict} |")

    if args.deep:
        lines += ["", "## Is a 'different' VAE just the fp16-fix VAE?", "",
                  "The fp16-fix VAE (`madebyollin/sdxl-vae-fp16-fix`) is SDXL's VAE with rescaled internals: same latent space, different weights.", ""]
        for n in ("SSD-1B", "Vega", "SDXL"):
            r = deep_compare(info[n]["repo"], "madebyollin/sdxl-vae-fp16-fix", "vae/diffusion_pytorch_model.fp16.safetensors", "diffusion_pytorch_model.safetensors")
            lines.append(f"- {n} VAE vs sdxl-vae-fp16-fix: {r}")
    report = "\n".join(lines) + "\n"
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(report)
    print(report)
    print(f"\nSummary: wrote {args.out}. A pair 'SHOULD WORK' only means the formats agree; Level 1's "
          "handoff image is still the real test.")


if __name__ == "__main__":
    main()
